#!/usr/bin/env python3
"""build_kb.py kb.txt kb.h [report.md]  - compiles facts, cue words and social acts into C arrays (no stored sentences)."""
import sys
REL = {'IS':1,'PROP':2,'HAS':3,'LIVES':4,'MADE':5,'CAN':6,'LIKES':7,'PART':8,'MIX':9,'ORBIT':10,'DO':11,'PRON':12,'NAMED':13,'ALIAS':14,'DEF':15}
words = []; wid = {}
def W(t):
    if t not in wid: wid[t] = len(words) + 2; words.append(t)
    return wid[t]
facts = []; cues = []; acts = []
for l in open(sys.argv[1]).read().splitlines():
    l = l.strip()
    if not l or l.startswith('#'): continue
    t = l.split()
    if t[0] == 'FACT':
        r = REL[t[2]]; s = W(t[1])
        if r == REL['NAMED']: o = W(t[3]); o2 = 0
        else: o = W(t[3]); o2 = W(t[4]) if len(t) > 4 else 0
        facts.append((s, r, o, o2))
    elif t[0] == 'ALIAS': facts.append((W(t[1]), REL['ALIAS'], W(t[2]), 0))
    elif t[0] == 'CUE': cues.append((W(t[1]), REL[t[2]]))
    elif t[0].startswith('ACT'):
        i = t.index('|'); acts.append((1 if t[0] == 'ACT&' else 0, [W(x) for x in t[1:i]], [W(x) for x in t[i+1:]]))
if len(words) > 253: sys.exit('too many words: %d' % len(words))
act = []
for flag, tr, rs in acts: act += [flag] + tr + [255] + rs + [0]
fb = [x for f in facts for x in f]; cb = [x for c in cues for x in c] + [0]
vstr = '\\0'.join(words)
def arr(n, d): return 'static const unsigned char %s[%d] = {%s};\n' % (n, len(d), ','.join(map(str, d)))
o = '/* generated by build_kb.py */\n#define NVOC %d\n#define NF %d\n#define NACT %d\n' % (len(words) + 2, len(facts), len(acts))
o += 'static const char vstr[] = "%s";\n' % vstr + arr('fact', fb) + arr('cue', cb) + arr('actd', act)
open(sys.argv[2], 'w').write(o)
size = sum(len(w) + 1 for w in words) + len(fb) + len(cb) + len(act)
print('words', len(words), 'facts', len(facts), 'cues', len(cues), 'acts', len(acts), 'bytes', size)
if len(sys.argv) > 3:
    names = {v: k for k, v in REL.items()}; w = lambda i: words[i - 2].replace('_', ' ') if i else ''
    lines = ['# Knowledge report (facts)\n', 'Words: %d, facts: %d, cue words: %d, social acts: %d, bytes: %d\n' % (len(words), len(facts), len(cues), len(acts), size), '## Facts (subject relation object)\n']
    lines += ['- %s %s %s %s' % (w(s), names[r], w(o), w(o2)) for s, r, o, o2 in facts]
    lines += ['\n## Cue words (they ask for a relation)\n', ', '.join('%s=%s' % (w(a), names[r]) for a, r in cues), '\n## Social acts\n']
    lines += ['- %s %s | %s' % ('ALL of' if f else 'ANY of', ' '.join(w(x) for x in t), ' '.join(w(x) for x in r)) for f, t, r in acts]
    open(sys.argv[3], 'w').write('\n'.join(lines) + '\n')
