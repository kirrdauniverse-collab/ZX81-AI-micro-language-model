#!/usr/bin/env python3
"""build_model.py corpus.txt model.h [report.md] [maxbytes]
Compiles a tokenised corpus (one sentence per line, UPPERCASE tokens, optional 'TRIGGER WORDS | RESPONSE', '!' = protected line) into C arrays:
vocabulary string, rarity weights, sentence store, successor lists. Prunes unprotected sentences until the vocabulary fits 253 words and the
model fits maxbytes (the space that is left after the code)."""
import sys, collections, math
STOP = set('A AN THE IS ARE AM WAS DO DOES YOU YOUR I MY ME IT TO OF AND IN ON AT WHAT WHO HOW CAN BY FOR WITH FROM THAT THIS THERE OR IF NOT TELL ABOUT MORE PLEASE'.split()) | set('. , ? !'.split())
TRIG = 255
maxbytes = int(sys.argv[4]) if len(sys.argv) > 4 else 10**9
def parse(l):
    if '|' in l:
        a, r = l.split('|'); return a.split() + ['<T>'] + r.split()
    return l.split()
raw = [l for l in open(sys.argv[1]).read().splitlines() if l.strip()]
prot = [i < 16 or l.startswith('!') for i, l in enumerate(raw)]
corpus = [parse(l.lstrip('!')) for l in raw]
dropped = []
def count(c): return collections.Counter(t for s in c for t in s if t != '<T>')
def build(corpus):
    freq = count(corpus)
    vocab = ['', '<END>'] + sorted(freq, key=lambda t: (-freq[t], t))
    ids = {t: i for i, t in enumerate(vocab)}
    def weight(t):
        if t in STOP: return 0
        return max(1, min(15, round(2.5 * math.log2(len(corpus) / freq[t]))))
    w = [0, 0] + [weight(t) for t in vocab[2:]]
    sent = []
    for s in corpus: sent += [TRIG if t == '<T>' else ids[t] for t in s] + [0]
    big = collections.defaultdict(set)
    for s in corpus:
        s2 = s[s.index('<T>') + 1:] if '<T>' in s else s
        seq = [ids[t] for t in s2] + [1]
        for a, b in zip(seq, seq[1:]): big[a].add(b)
    bdat = []
    for t in range(len(vocab)):
        bdat += sorted(big.get(t, ())) + [0]
    vstr = '\\0'.join(vocab[2:])
    size = sum(len(t) + 1 for t in vocab[2:]) + len(w) + len(sent) + len(bdat)
    return freq, vocab, ids, w, sent, bdat, vstr, size
while True:
    freq, vocab, ids, w, sent, bdat, vstr, size = build(corpus)
    if len(vocab) <= 254 and size <= maxbytes: break
    cand = [(sum(1 for t in s if t != '<T>' and freq[t] == 1), -len(s), i) for i, s in enumerate(corpus) if not prot[i]]
    if not cand: sys.exit('protected lines alone do not fit: %d words, %d bytes' % (len(vocab) - 2, size))
    _, _, i = max(cand)
    dropped.append(' '.join(corpus[i])); del corpus[i]; del prot[i]
def arr(name, data): return 'static const unsigned char %s[%d] = {%s};\n' % (name, len(data), ','.join(str(x) for x in data))
o = '/* generated by build_model.py - do not edit */\n#define NVOC %d\n#define NSENT %d\n' % (len(vocab), len(corpus))
o += 'static const char vstr[] = "%s";\n' % vstr.replace('"', '\\"') + arr('vw', w) + arr('sent', sent) + arr('bdat', bdat)
open(sys.argv[2], 'w').write(o)
print('vocab', len(vocab) - 2, 'sentences', len(corpus), 'dropped', len(dropped), 'model bytes', size)
if len(sys.argv) > 3:
    r = ['# Knowledge report (generated by tools/build_model.py)\n', 'Model size: %d bytes. Vocabulary: %d words (limit 253). Sentences kept: %d. Links: %d.\n' % (size, len(vocab) - 2, len(corpus), len(bdat))]
    r.append('## Sentences in memory (trigger | response)\n'); r += ['- ' + ' '.join(s).replace('<T>', '|') for s in corpus]
    r.append('\n## Dropped (did not fit)\n'); r += ['- ' + d for d in dropped]
    r.append('\n## Vocabulary (word, uses, weight)\n'); r.append(', '.join('%s(%d,%d)' % (t, freq[t], w[ids[t]]) for t in vocab[2:]))
    open(sys.argv[3], 'w').write('\n'.join(r) + '\n')
