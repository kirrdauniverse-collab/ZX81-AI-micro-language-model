#!/usr/bin/env python3
"""build_model.py corpus.txt model.h  -- compile a tokenised corpus (one sentence per line, space separated
tokens, UPPERCASE) into C arrays: vocabulary, rarity weights, sentence store, bigram successor table."""
import sys, collections
import math
STOP = set('A AN THE IS ARE AM WAS DO DOES YOU YOUR I MY ME IT TO OF AND IN ON AT WHAT WHO HOW CAN BY FOR WITH FROM THAT THIS THERE OR IF NOT'.split()) | set('. , ? !'.split())
TRIG = 255
def parse(l):
    if '|' in l:
        a, r = l.split('|'); return a.split() + ['<T>'] + r.split()
    return l.split()
corpus = [parse(l) for l in open(sys.argv[1]).read().splitlines() if l.strip()]
dropped = []
PROTECT = 16          # the first lines (greeting, identity) are never dropped
def count(c): return collections.Counter(t for s in c for t in s if t != '<T>')
freq = count(corpus)
while len(freq) + 2 > 254:    # prune the sentences that bring the most single-use words
    cand = [(sum(1 for t in s if freq[t] == 1), -len(s), i) for i, s in enumerate(corpus) if i >= PROTECT]
    _, _, i = max(cand)
    dropped.append(' '.join(corpus[i]))
    del corpus[i]; freq = count(corpus)
# ids: 0 = terminator, 1 = END, words from 2
vocab = ['', '<END>'] + sorted(freq, key=lambda t: (-freq[t], t))
ids = {t: i for i, t in enumerate(vocab)}
if len(vocab) > 254: sys.exit('vocab too large: %d' % len(vocab))
mx = max(freq.values())
def weight(t):
    if t in STOP: return 0
    return max(1, min(15, round(2.5 * math.log2(len(corpus) / freq[t]))))   # rare words weigh more
w = [0, 0] + [weight(t) for t in vocab[2:]]
sent = []; sidx = []
for s in corpus:
    sidx.append(len(sent)); sent += [TRIG if t == '<T>' else ids[t] for t in s] + [0]
big = collections.defaultdict(collections.Counter)
for s in corpus:
    s2 = s[s.index('<T>') + 1:] if '<T>' in s else s
    seq = [ids[t] for t in s2] + [1]
    for a, b in zip(seq, seq[1:]): big[a][b] += 1
boff = []; bdat = []
for t in range(len(vocab)):
    boff.append(len(bdat))
    for n, c in sorted(big.get(t, {}).items()): bdat += [n, min(c, 255)]
    bdat.append(0)
boff.append(len(bdat))
vstr = b''.join(t.encode() + b'\0' for t in vocab[2:])
voff = []; p = 0
for t in vocab[2:]: voff.append(p); p += len(t) + 1
def arr(name, typ, data):
    return 'static const %s %s[%d] = {%s};\n' % (typ, name, len(data), ','.join(str(x) for x in data))
o = '/* generated by build_model.py - do not edit */\n'
o += '#define NVOC %d\n#define NSENT %d\n' % (len(vocab), len(sidx))
o += 'static const char vstr[] = "%s";\n' % '\\0'.join(vocab[2:]).replace('"', '\\"')
o += arr('vw', 'unsigned char', w) + arr('sent', 'unsigned char', sent)
o += arr('sidx', 'unsigned int', sidx) + arr('bdat', 'unsigned char', bdat)   # words and successor lists are scanned in order: no offset tables
open(sys.argv[2], 'w').write(o)
print('vocab', len(vocab), 'sentences', len(sidx), 'bytes: vocab %d voff %d w %d sent %d sidx %d boff %d bdat %d' % (
    len(vstr), 0, len(w), len(sent), 2*len(sidx), 0, len(bdat)),
    'TOTAL', len(vstr)+len(w)+len(sent)+2*len(sidx)+len(bdat))

if len(sys.argv) > 3:
    r = ['# Knowledge report (generated by tools/build_model.py)\n']
    tot = len(vstr)+len(w)+len(sent)+2*len(sidx)+len(bdat)
    r.append('Model size: %d bytes. Vocabulary: %d words (limit 253). Sentences kept: %d. Bigram pairs: %d.\n' % (tot, len(vocab)-2, len(sidx), len(bdat)//2))
    r.append('## Sentences in memory (trigger | response)\n')
    for s in corpus: r.append('- ' + ' '.join(s).replace('<T>', '|'))
    r.append('\n## Dropped (did not fit the 253-word limit)\n')
    for d in dropped: r.append('- ' + d)
    r.append('\n## Vocabulary (word, uses, weight)\n')
    r.append(', '.join('%s(%d,%d)' % (t, freq[t], w[ids[t]]) for t in vocab[2:]))
    open(sys.argv[3], 'w').write('\n'.join(r) + '\n')
